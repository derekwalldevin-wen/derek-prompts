#!/usr/bin/env python3
"""Build the德里克文 prompt gallery.

Source of truth : ../data/prompts.json   (prompt text is never rewritten here)
Outputs         : site/data/prompts.js   (runtime data for the page)
                  docs/                  (deployable folder for GitHub Pages)

Usage:
    cd site && python build.py          # build site runtime data + docs/
    python build.py --no-docs           # only rebuild site/data/prompts.js
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA = ROOT / "data" / "prompts.json"
IMG = HERE / "img"
DOCS = ROOT / "docs"

CAT_ZH = {"image": "图像", "video": "视频", "text": "文本"}


def load() -> list[dict]:
    if not DATA.exists():
        raise SystemExit(f"missing source data: {DATA}")
    entries = json.loads(DATA.read_text(encoding="utf-8"))
    if not isinstance(entries, list) or not entries:
        raise SystemExit("data/prompts.json is empty or not a list")
    return entries


def entry_file(entry: dict) -> str:
    """Find entries/<id>-<slug>.md for the 'Markdown 原文' link."""
    hits = sorted((ROOT / "entries").glob(f"{entry['id']}-*.md"))
    return f"entries/{hits[0].name}" if hits else ""


def normalize(entries: list[dict]) -> list[dict]:
    cards = []
    for n, d in enumerate(entries):
        cat = d.get("category", "")
        media = []
        for m in d.get("media") or []:
            src = m.get("src") or ""
            if src and (IMG / Path(src).name).exists():
                media.append({"src": src, "w": int(m.get("w") or 0), "h": int(m.get("h") or 0)})
        # legacy entries (before localisation) fall back to remote urls
        if not media:
            for src in d.get("media_preview_urls") or []:
                if Path(src).suffix.lower() in {".webp", ".jpg", ".jpeg", ".png"} and (IMG / Path(src).name).exists():
                    media.append({"src": src, "w": 0, "h": 0})
                elif src.startswith("http"):
                    media.append({"src": src, "w": 0, "h": 0})
        prompt = d.get("prompt") or ""
        prompts = d.get("prompts") or [{"name": "提示词", "text": prompt}]
        cards.append(
            {
                "id": str(d.get("id", "")),
                "no": n + 1,
                "title": d.get("title", ""),
                "desc": d.get("description") or d.get("desc") or "",
                "cat": CAT_ZH.get(cat, cat or "图像"),
                "models": d.get("models") or [],
                "date": d.get("date") or "",
                "source": d.get("x_url") or d.get("source") or "",
                "images": [m["src"] for m in media],
                "media": media,
                "prompts": prompts,
                "notes": d.get("notes") or "",
                "file": d.get("file") or entry_file(d),
            }
        )
    cards.sort(key=lambda c: (c["date"], c["id"]), reverse=True)
    for i, c in enumerate(cards):
        c["no"] = i + 1
    return cards


def write_data(cards: list[dict]) -> None:
    out = HERE / "data"
    out.mkdir(parents=True, exist_ok=True)
    js = "/* generated by build.py — do not edit */\nwindow.DEREK_PROMPTS = "
    js += json.dumps(cards, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (out / "prompts.js").write_text(js, encoding="utf-8")
    legacy = out / "prompts.json"
    if legacy.exists():
        legacy.unlink()


def sync_entries() -> None:
    """Mirror ../entries into site/entries so the 'Markdown 原文' link works in local preview."""
    src = ROOT / "entries"
    dst = HERE / "entries"
    if not src.is_dir():
        return
    dst.mkdir(exist_ok=True)
    for f in src.glob("*.md"):
        target = dst / f.name
        if not target.exists() or target.stat().st_size != f.stat().st_size:
            shutil.copy2(f, target)


DEFAULT_BASE = "https://derekwalldevin-wen.github.io/derek-prompts"


def build_docs(target: Path | None = None, base: str | None = None, mirror: str | None = None) -> Path:
    """把站点打成可部署目录。

    base   改写 canonical / og:url / og:image 的绝对域名（GitHub 版与国内版各一个）
    mirror 页脚互链的对站地址：GitHub 版填国内镜像，国内版填 GitHub 版
    """
    out = target or DOCS
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    html = (HERE / "index.html").read_text(encoding="utf-8")
    base = (base or DEFAULT_BASE).rstrip("/")
    if base != DEFAULT_BASE:
        html = html.replace(DEFAULT_BASE, base)
    if mirror:
        label = "GitHub 版" if "github.io" in mirror else "国内镜像"
        html = html.replace(
            "<!--MIRROR-->",
            f'<a href="{mirror.rstrip("/")}/" target="_blank" rel="noopener">{label} ↗</a><span> · </span>',
        )
    else:
        html = html.replace("<!--MIRROR-->", "")
    (out / "index.html").write_text(html, encoding="utf-8")
    (out / "data").mkdir()
    shutil.copy2(HERE / "data" / "prompts.js", out / "data" / "prompts.js")
    for folder in ("img", "fonts", "entries"):
        src = HERE / folder
        if src.is_dir():
            shutil.copytree(src, out / folder)
    (out / ".nojekyll").write_text("", encoding="utf-8")
    for extra in ("og.jpg", "README.md"):
        src = HERE / extra if extra == "og.jpg" else ROOT / extra
        if src.exists():
            shutil.copy2(src, out / extra)
    return out


def report(cards: list[dict]) -> None:
    img = sum(1 for c in cards if c["cat"] == "图像")
    vid = sum(1 for c in cards if c["cat"] == "视频")
    local = sum(len(c["media"]) for c in cards)
    print(f"cards={len(cards)} image={img} video={vid} local_images={local}")
    empty = [c["id"] for c in cards if not c["media"]]
    if empty:
        print("WARNING: entries without media:", ", ".join(empty))
    baseline_path = ROOT / "data" / "expected.json"
    baseline = json.loads(baseline_path.read_text(encoding="utf-8")) if baseline_path.exists() else {"total": 42}
    if len(cards) < baseline["total"]:
        print(f"WARNING: 条目数 {len(cards)} 少于基线 {baseline['total']} —— 数据可能丢了", file=sys.stderr)


def main(argv: list[str]) -> None:
    cards = normalize(load())
    write_data(cards)
    sync_entries()
    target = None
    base = None
    mirror = None
    if "--out" in argv:
        target = Path(argv[argv.index("--out") + 1]).resolve()
    if "--base" in argv:
        base = argv[argv.index("--base") + 1]
    if "--mirror" in argv:
        mirror = argv[argv.index("--mirror") + 1]
    out_dir = None
    if "--no-docs" not in argv:
        out_dir = build_docs(target, base, mirror)
    report(cards)
    print("site/data/prompts.js written" + ("" if out_dir is None else f"; 部署目录: {out_dir}"))


if __name__ == "__main__":
    main(sys.argv[1:])
